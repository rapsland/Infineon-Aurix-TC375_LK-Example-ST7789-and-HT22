// Main function
void core0_main(void) {
    initSystem();
    uint32_t lastTickTime = getStmTicks();
    uint32_t targetInterval = g_ticksFor1s; // 1 second in ticks
    
    while(1) {
        uint32_t currentTicks = getStmTicks();
        uint32_t elapsedTicks = currentTicks - lastTickTime;
        
        // Calculate wait time compensating for processing delay
        uint32_t adjustedWait = (elapsedTicks < targetInterval) ? 
                               (targetInterval - elapsedTicks) : 0;
        
        // Get time readings first
        gm_time = getTime();
        gm_rawtime = getRawTime();
        
        // Process sensors and update display
        processDHT22Data();
        extern float humidity, temperature;
        updateSensor(&g_humidity, humidity);
        updateSensor(&g_temperature, temperature);
        displayReadings();
        
        // Store sensor data every 15 minutes
        if ((currentTicks - lastStoreTime) >= IfxStm_getTicksFromMilliseconds(&MODULE_STM0, STORE_INTERVAL_MS)) {
            //storeSensorData();
            lastStoreTime = currentTicks;
        }
        
        // Calculate elapsed time after processing
        currentTicks = getStmTicks();
        elapsedTicks = currentTicks - lastTickTime;
        
        // Calculate wait time compensating for processing delay
        adjustedWait = (elapsedTicks < targetInterval) ? 
                      (targetInterval - elapsedTicks) : 0;
        
        // Wait remaining time to maintain precise 1-second interval
        if (adjustedWait > 0) {
            waitTime(adjustedWait);
        }
        
        // Update last tick time for next iteration
        lastTickTime = getStmTicks();
    }
}

static void initSystem(void) {
    IfxCpu_enableInterrupts();
    IfxScuWdt_disableCpuWatchdog(IfxScuWdt_getCpuWatchdogPassword());
    IfxScuWdt_disableSafetyWatchdog(IfxScuWdt_getSafetyWatchdogPassword());
    
    IfxCpu_emitEvent(&g_cpuSyncEvent);
    IfxCpu_waitEvent(&g_cpuSyncEvent, 1);
    
    g_ticksFor1s = IfxStm_getTicksFromMilliseconds(BSP_DEFAULT_TIMER, WAIT_TIME);
    
    ST7789_Init();
    ST7789_FillScreen(ST7789_BLACK);
    createBox();
    
    ST7789_Print(20, 10, "- Aurix TC375TP Test Program -", ST7789_WHITE, ST7789_BLACK, 1);
    ST7789_Print(10, 30, "Core0 run", ST7789_BLUE, ST7789_BLACK, 2);

    // Read sensor data from flash
    readSensorDataFromFlash(&g_sensorData);

    // Initialize global variables with sensor data
    g_humidity.max = g_sensorData.maxHumidity;
    g_humidity.min = g_sensorData.minHumidity;
    g_humidity.maxTime = g_sensorData.maxHumidityTime;
    g_humidity.minTime = g_sensorData.minHumidityTime;

    g_temperature.max = g_sensorData.maxTemperature;
    g_temperature.min = g_sensorData.minTemperature;
    g_temperature.maxTime = g_sensorData.maxTemperatureTime;
    g_temperature.minTime = g_sensorData.minTemperatureTime;
}

static void updateSensor(SensorReading* reading, float newValue) {
    reading->value = newValue;
    
    if (newValue > reading->max) {
        reading->max = newValue;
        reading->maxTime = gm_time;
    }
    if (newValue < reading->min) {
        reading->min = newValue;
        reading->minTime = gm_time;
    }
}

static void storeSensorData(void) {
    g_sensorData.maxHumidity = g_humidity.max;
    g_sensorData.minHumidity = g_humidity.min;
    g_sensorData.maxHumidityTime = g_humidity.maxTime;
    g_sensorData.minHumidityTime = g_humidity.minTime;
    g_sensorData.maxTemperature = g_temperature.max;
    g_sensorData.minTemperature = g_temperature.min;
    g_sensorData.maxTemperatureTime = g_temperature.maxTime;
    g_sensorData.minTemperatureTime = g_temperature.minTime;

    writeSensorDataToFlash(&g_sensorData);
}

