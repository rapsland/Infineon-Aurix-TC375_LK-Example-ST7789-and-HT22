// Add safe timer conversion function
static uint32_t getStmTicks(void) {
    uint64_t ticks = IfxStm_get(&MODULE_STM0);
    // Handle potential overflow, keep lower 32 bits
    return (uint32_t)(ticks & 0xFFFFFFFF);
}

// Update function prototype to use uint32_t
void delay_ms(uint32_t ms);

// Update function implementation
void delay_ms(uint32_t ms) {
    uint32_t ticksFor1ms = IfxStm_getTicksFromMilliseconds(&MODULE_STM0, 1);
    uint32_t startTime = getStmTicks();
    while ((getStmTicks() - startTime) < (ticksFor1ms * ms)) {}
}

// Format time string as "HH:MM:SS"
static void mySprint(char *buffer, uint8_t hours, uint8_t minutes, uint8_t seconds)
{
    // Format hours
    if (hours < 10) {
        *buffer++ = '0';
        *buffer++ = '0' + hours;
    } else {
        *buffer++ = '0' + (hours / 10);
        *buffer++ = '0' + (hours % 10);
    }
    
    // Add colon
    *buffer++ = ':';
    
    // Format minutes
    if (minutes < 10) {
        *buffer++ = '0';
        *buffer++ = '0' + minutes;
    } else {
        *buffer++ = '0' + (minutes / 10);
        *buffer++ = '0' + (minutes % 10);
    }
    
    // Add colon
    *buffer++ = ':';
    
    // Format seconds
    if (seconds < 10) {
        *buffer++ = '0';
        *buffer++ = '0' + seconds;
    } else {
        *buffer++ = '0' + (seconds / 10);
        *buffer++ = '0' + (seconds % 10);
    }
    
    // Add null terminator
    *buffer = '\0';
}

